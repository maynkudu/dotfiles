import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { advanceSpring } from '/home/maynkudu/Code/Projects/apple-design-and-animation-system/skills/apple-design-and-animation/scripts/motion.mjs';

const dir = fileURLToPath(new URL('.', import.meta.url));
const checks = [], browser = (...args) => {
  const result = spawnSync('agent-browser', ['--session', 'skill-forward-test', '--json', ...args], { encoding: 'utf8' });
  if (result.status !== 0) throw Error(result.stdout + result.stderr);
  const output = JSON.parse(result.stdout);
  if (!output.success) throw Error(JSON.stringify(output));
  return output.data;
};
const evaluate = script => browser('eval', script).result;
const state = () => evaluate('window.panelFixture.inspect()');
const rest = () => evaluate('new Promise(resolve => { function check() { if (!window.panelFixture.inspect().rafPending) resolve(window.panelFixture.inspect()); else requestAnimationFrame(check); } check(); })');
const geometry = () => evaluate(`({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,overflows:[...document.querySelectorAll('main *')].filter(el=>{const r=el.getBoundingClientRect();return r.width>0&&(r.right>innerWidth+.5||r.left<-.5)}).map(el=>el.id||el.tagName)})`);
try {
  browser('set', 'media', 'light'); browser('set', 'viewport', '1000', '820');
  browser('reload');
  for (const sample of [{position:1,velocity:0,target:2,omega:20,dampingRatio:.85},{position:1.8,velocity:3.7,target:0,omega:20,dampingRatio:.85}]) {
    const actual = evaluate(`window.panelFixture.advanceSpring(${JSON.stringify(sample)}, 0.137)`);
    assert.deepEqual(actual, advanceSpring(sample, .137));
  }
  checks.push('The HTML spring and skill sampler return identical position and velocity for forward motion and opposing-velocity reversal.');
  assert.deepEqual(state().draft, { exposure: .3, placement: 1 });
  browser('fill', '#exposure-number', '');
  assert.equal(state().draft.exposure, .3);
  assert.equal(state().invalidNumber, true);
  assert.equal(evaluate("document.getElementById('save').disabled"), true);
  browser('press', 'Enter');
  assert.equal(state().invalidNumber, false);
  browser('fill', '#exposure-number', '3');
  assert.equal(state().draft.exposure, .3);
  assert.equal(state().invalidNumber, true);
  browser('press', 'Enter');
  assert.equal(state().draft.exposure, 2);
  browser('fill', '#exposure-number', '0.35');
  assert.equal(state().draft.exposure, 2);
  browser('press', 'Enter');
  assert.equal(state().draft.exposure, .4);
  checks.push('Empty and invalid numeric input preserve the semantic value and block Save. Enter restores empty input, clamps range and rounds to 0.1.');
  browser('focus', '#exposure');
  browser('press', 'Home'); assert.equal(state().draft.exposure, -2);
  browser('press', 'ArrowRight'); assert.equal(state().draft.exposure, -1.9);
  browser('press', 'End'); assert.equal(state().draft.exposure, 2);
  assert.equal(evaluate("document.getElementById('exposure-number').value"), '2.0');
  assert.equal(evaluate("document.getElementById('exposure').getAttribute('aria-valuetext')"), '+2.0 EV');
  checks.push('Native slider Home, End and ArrowRight operate the -2 to 2 grid and synchronize numeric entry and accessible value.');
  const box = evaluate("(() => { const r=document.getElementById('exposure').getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height}; })()");
  browser('mouse', 'move', String(Math.round(box.x + box.width - 8)), String(Math.round(box.y + box.height / 2)));
  browser('mouse', 'down');
  browser('mouse', 'move', String(Math.round(box.x - 80)), String(Math.round(box.y + box.height / 2)));
  browser('mouse', 'up'); assert.equal(state().draft.exposure, -2);
  browser('mouse', 'move', String(Math.round(box.x + 8)), String(Math.round(box.y + box.height / 2)));
  browser('mouse', 'down');
  browser('mouse', 'move', String(Math.round(box.x + box.width + 80)), String(Math.round(box.y + box.height / 2)));
  browser('mouse', 'up'); assert.equal(state().draft.exposure, 2);
  checks.push('Real mouse drags beyond both slider endpoints retain bounded -2 and 2 semantic values.');
  browser('fill', '#exposure-number', '1.2');
  browser('press', 'Enter');
  browser('click', '[name=placement][value="2"]');
  browser('click', '#save'); assert.deepEqual(state().saved, { exposure: 1.2, placement: 2 });
  browser('fill', '#exposure-number', '-1'); browser('press', 'Enter');
  browser('click', '[name=placement][value="0"]');
  assert.deepEqual(state().saved, { exposure: 1.2, placement: 2 });
  browser('click', '#restore');
  assert.deepEqual(state().draft, { exposure: 1.2, placement: 2 });
  rest(); assert.equal(state().spring.position, 2);
  checks.push('Save commits both draft values. Later edits leave saved values intact. Restore returns both controls and preview to the last save.');
  browser('click', '[name=placement][value="0"]'); rest();
  browser('click', '[name=placement][value="2"]');
  browser('click', '[name=placement][value="0"]');
  const interrupted = state().trace.at(-1);
  assert.ok(interrupted.before.velocity > 0, JSON.stringify(interrupted));
  assert.deepEqual(interrupted.before, interrupted.after);
  rest(); assert.equal(state().spring.position, 0);
  checks.push(`Real radio clicks reverse active motion with unchanged position and velocity. Preserved opposing velocity ${interrupted.before.velocity.toFixed(6)} intervals/s.`);
  browser('focus', '[name=placement][value="0"]'); browser('press', 'ArrowRight');
  assert.equal(state().draft.placement, 1);
  checks.push('Native radio ArrowRight changes the selected placement and targets the same spring.');
  browser('click', '[name=placement][value="2"]');
  browser('set', 'media', 'light', 'reduced-motion');
  assert.equal(state().reducedMotion, true);
  assert.equal(state().rafPending, false);
  assert.equal(state().spring.position, 2);
  browser('click', '[name=placement][value="0"]');
  assert.equal(state().spring.position, 0); assert.equal(state().rafPending, false);
  browser('reload'); assert.equal(state().reducedMotion, true);
  browser('click', '[name=placement][value="2"]');
  assert.equal(state().spring.position, 2); assert.equal(state().rafPending, false);
  checks.push('Hot reduced-motion preference stops the JavaScript spring. Startup reduced motion and later choices select the destination immediately.');
  browser('set', 'media', 'light'); browser('reload');
  const source = await readFile(new URL('./panel.html', import.meta.url), 'utf8');
  const sample = source.match(/const svg = `([\s\S]*?)`;/)[1];
  await writeFile(new URL('./sample.svg', import.meta.url), sample);
  browser('upload', '#photo-file', dir + 'sample.svg');
  const upload = evaluate("new Promise(resolve => { const image=document.getElementById('photo');function check(){if(image.src.startsWith('blob:')&&image.complete)resolve({name:document.getElementById('image-name').textContent,width:image.naturalWidth});else requestAnimationFrame(check)}check(); })");
  assert.equal(upload.name, 'sample.svg'); assert.ok(upload.width > 0);
  checks.push('Local file upload loads a selected image through an owned object URL.');
  browser('reload'); browser('set', 'viewport', '320', '820');
  const narrow = geometry(); assert.equal(narrow.scrollWidth, 320); assert.deepEqual(narrow.overflows, []);
  browser('screenshot', dir + 'narrow.png');
  evaluate("document.documentElement.style.fontSize='32px'");
  const enlarged = geometry(); assert.equal(enlarged.scrollWidth, 320); assert.deepEqual(enlarged.overflows, []);
  assert.equal(evaluate("getComputedStyle(document.getElementById('segments')).gridTemplateColumns.split(' ').length"), 1);
  assert.equal(evaluate("[...document.querySelectorAll('.segments label')].some(el=>el.scrollWidth>el.clientWidth+1)"), false);
  browser('screenshot', dir + 'enlarged.png', '--full');
  checks.push('320px viewport and 200% rem text fixture retain controls without horizontal viewport overflow. Enlarged placement labels stack and do not clip.');
  evaluate("document.documentElement.style.fontSize='16px'");
  browser('set', 'media', 'dark');
  assert.equal(evaluate("getComputedStyle(document.getElementById('save')).color"), 'rgb(187, 193, 204)');
  browser('screenshot', dir + 'dark.png');
  checks.push('Dark-theme rendering captured at 320px.');
  browser('set', 'media', 'light');
  browser('set', 'viewport', '1000', '820');
  browser('screenshot', dir + 'wide.png');
  const errors = browser('errors');
  assert.equal(errors.errors.length, 0, JSON.stringify(errors));
  checks.push('Browser reported no runtime page errors.');
  await writeFile(new URL('./browser-evidence.json', import.meta.url), JSON.stringify({ passed: true, browser: 'Agent Browser, owned Chromium session skill-forward-test', checks, interrupted, narrow, enlarged, errors }, null, 2) + '\n');
  console.log(checks.join('\n'));
} catch (error) {
  await writeFile(new URL('./browser-evidence.json', import.meta.url), JSON.stringify({ passed: false, checks, failure: String(error) }, null, 2) + '\n');
  throw error;
}
